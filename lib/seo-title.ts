/**
 * Returns the shortest usable brand form for this university. Used only
 * when the standard clampTitle output has dropped the fee segment. Prefers
 * the University.shortName field (source-of-truth, added Sprint 2), then
 * falls back to stripping "University" / "Univ" off the TITLE_NAME entry,
 * then to getTitleName. Never invents an abbreviation.
 */
export function getShortTitleName(
  id: string,
  shortName: string | undefined,
  name: string,
  abbr: string,
): string {
  if (shortName && shortName.trim()) return shortName.trim()
  const full = TITLE_NAME[id] ?? getTitleName(id, name, abbr)
  const stripped = full.replace(/\s+(University|Univ)$/i, '').trim()
  return stripped.length >= 3 ? stripped : full
}

/**
 * Fee-led title builder. Builds a title with the full university name first;
 * if clampTitle drops the fee segment, retries with the shortName. Priority
 * order the caller must respect when composing `full` and `short`:
 *   brand suffix (reserved by clampTitle) >
 *   programme + "Fees {year}" (part of the anchor before ": ") >
 *   fee (leftmost segment after ": ") >
 *   NAAC (next segment) >
 *   NIRF (last segment).
 *
 * The retry with `short` fires only when the greedy right-to-left segment
 * drop couldn't keep the fee. That way Sprint 1 titles that already fit
 * with the full name never regress.
 */
/**
 * Spec-page variant of clampTitleFeeLed. The specialisation token is what makes
 * one spec page different from its siblings, and clampTitle drops the tail
 * first, so a long university name pushed it out: all three Kurukshetra M.Com
 * "General Commerce" pages rendered the identical title. Retry with the short
 * university name, which buys enough room to keep the spec and the year.
 * Measured 2026-08-30: 214 of 2,066 spec titles were over the limit, 142 of
 * them fit once the university name is shortened.
 */
export function clampTitleSpecLed(
  full: string,
  short: string,
  specToken: string,
  max = 60,
): string {
  const clamped = clampTitle(full, max)
  if (!specToken || clamped.includes(specToken)) return clamped
  if (short === full) return clamped
  const retry = clampTitle(short, max)
  return retry.includes(specToken) ? retry : clamped
}

export function clampTitleFeeLed(
  full: string,
  short: string,
  feeToken: string | null,
  max = 60,
): string {
  const clamped = clampTitle(full, max)
  if (!feeToken || clamped.includes(feeToken)) return clamped
  if (short === full) return clamped
  const retry = clampTitle(short, max)
  return retry.includes(feeToken) ? retry : clamped
}

/**
 * Returns a short university name (≤25 chars) suitable for page titles.
 * Falls back to a cleaned/truncated version of the full name, or the abbreviation.
 */
export function getTitleName(id: string, name: string, abbr: string): string {
  if (TITLE_NAME[id]) return TITLE_NAME[id]

  // Clean: strip trailing "Online" and parenthetical suffixes
  const cleaned = name
    .replace(/\s*\(.*?\)\s*/g, '')
    .replace(/\s+[Oo]nline\s*$/, '')
    .trim()

  if (cleaned.length <= 25) return cleaned

  // Truncate to 25 chars at a word boundary
  const truncated = cleaned.substring(0, 25).replace(/\s+\S*$/, '').trim()
  if (truncated.length >= 10) return truncated

  // Last resort: use abbreviation
  return abbr || cleaned.substring(0, 25)
}

// Words that must never be left dangling at the end of a truncated name.
const TRAILING_STOPWORDS = /(?:\s+(?:of|and|for|the|in|to|&|at|on|with))+$/i

/**
 * Shortens an institution's own legal name for use in a page title, using
 * nothing but that name. Never consults a slug, an id or a lookup table, so it
 * cannot attribute one university's short name to another. That matters on
 * /verify/, where three Manipal entities and two DY Patil entities each have
 * their own page.
 *
 * Used by app/verify/[slug]/generateMetadata for the 58 verify slugs whose
 * Supabase slug is not a lib/data.ts id. getUniversityById returns null for
 * every one of them, so before this the full legal name went straight into
 * the title: 90 and 97 characters on the NMIMS and Shoolini pages, both far
 * past Google's ~60-char cut, both sitting at position 7.5-8.5 with 0 clicks
 * on 120-128 impressions in the 28-day GSC export (2026-08-29).
 *
 * Order matters:
 *  1. A name already inside budget is returned untouched, so disambiguating
 *     suffixes survive. "Dr. D.Y. Patil Vidyapeeth (Pune)" is 32 chars and
 *     must keep its "(Pune)" to stay distinct from "D.Y. Patil (Navi Mumbai)".
 *  2. Only once a name is over budget does a bracketed acronym win, because
 *     that acronym is the term people actually search: NMIMS, HITS, VISTAS.
 *  3. Otherwise drop the brackets, then truncate on a word boundary.
 */
export function shortenInstitutionName(name: string, max = 26): string {
  const s = name.replace(/\s+[Oo]nline\s*$/, '').trim()
  if (s.length <= max) return s

  // A bracketed token only counts as an acronym when it is genuinely
  // capitalised. Requiring two capitals keeps NMIMS, HITS and VISTAS while
  // rejecting "(Pune)", which is a disambiguator and would be actively wrong
  // as a university name.
  const bracketed = s.match(/\(([A-Z][A-Za-z.&]{2,7})\)/)
  const acronym = bracketed && (bracketed[1].match(/[A-Z]/g) || []).length >= 2
    ? bracketed[1]
    : null
  if (acronym) return acronym

  const base = s.replace(/\s*\(.*?\)\s*/g, ' ').replace(/\s+/g, ' ').trim()
  if (base.length <= max) return base

  const truncated = base
    .substring(0, max)
    .replace(/\s+\S*$/, '')
    .replace(TRAILING_STOPWORDS, '')
    .replace(/[\s,;:.\-&]+$/, '')
    .trim()

  return truncated.length >= 8 ? truncated : base.substring(0, max).trim()
}

