// Maximum length of a shortened specialisation label. Was an implicit 22 with a
// hard substring cut, which collapsed distinct specialisations at the same
// university onto one title: "Finance and International Business" and "Finance
// and Operations Management" both became "Finance and". Seven such groups
// covering 15 pages were shipping duplicate titles.
const SHORT_SPEC_MAX = 26

// Never leave one of these as the last word. "Finance and" is both unreadable
// and non-distinguishing.
const SPEC_TRAILING_STOPWORDS = new Set([
  'and', 'or', 'for', 'of', 'the', 'with', 'in', 'on', 'a', 'an', 'to', '&', '-', '\u2013',
])

// Applied before any truncation so the distinguishing tail of a long spec
// survives instead of being cut away.
const SPEC_ABBREVIATIONS: [RegExp, string][] = [
  [/\bInternational\b/g, 'Intl'],
  [/\bManagement\b/g, 'Mgmt'],
  [/\bAdministration\b/g, 'Admin'],
  [/\bTechnologies\b/g, 'Tech'],
  [/\bTechnology\b/g, 'Tech'],
  [/\bApplications\b/g, 'Apps'],
  [/\bEnvironmental\b/g, 'Env'],
  [/\bDevelopment\b/g, 'Dev'],
  [/\bEngineering\b/g, 'Engg'],
]

// The Excel source truncates some specialisation names mid-phrase and leaves an
// unclosed bracket behind, e.g. "General Commerce (Taxation" and "Computer
// Applications (4 specialisations available". Drop the stray bracket and keep
// the words, which are the part that makes the label distinct.
function tidySpecLabel(spec: string): string {
  let s = spec
  // "Computer Applications (4 specialisations available" is a count, not part of
  // the specialisation's name, and it produced the title "Computer Apps 4".
  s = s.replace(/\(?\s*\d+\s+specialisations?\s+available\)?/gi, ' ')
  const open = (s.match(/\(/g) || []).length
  const close = (s.match(/\)/g) || []).length
  if (open !== close) s = s.replace(/[()]/g, ' ')
  return s.replace(/\s+/g, ' ').trim()
}

// Trim on a word boundary, then drop any trailing stopword.
function trimSpecToWords(s: string, max: number): string {
  if (s.length <= max) return s
  const out: string[] = []
  for (const w of s.split(' ')) {
    if (out.length && [...out, w].join(' ').length > max) break
    out.push(w)
  }
  while (out.length > 1 && SPEC_TRAILING_STOPWORDS.has(out[out.length - 1].toLowerCase())) out.pop()
  return out.join(' ').trim()
}

export function shortenSpec(spec: string): string {
  if (SPEC_MAP[spec]) return SPEC_MAP[spec]
  const cleaned = tidySpecLabel(spec)
  if (cleaned.length <= SHORT_SPEC_MAX) return cleaned

  // BCA specs follow the pattern "Computer Applications - Data Science".
  // Strip the common prefix so each specialization page gets a distinct token.
  const caMatch = cleaned.match(/^Computer Applications\s*[\u2013\u2014-]\s*(.+)$/)
  if (caMatch) {
    const suffix = caMatch[1].trim()
    return suffix.length <= 30 ? suffix : trimSpecToWords(suffix, 30)
  }

  let abbreviated = cleaned
  for (const [re, rep] of SPEC_ABBREVIATIONS) abbreviated = abbreviated.replace(re, rep)
  abbreviated = abbreviated.replace(/\s+/g, ' ').trim()
  if (abbreviated.length <= SHORT_SPEC_MAX) return abbreviated

  return trimSpecToWords(abbreviated, SHORT_SPEC_MAX)
}


/**
 * Collapse a CMS-supplied fee string when min and max are identical, so titles
 * read "₹77K" instead of "₹77K – ₹77K" or "₹77K - ₹77K". Idempotent for fee
 * strings that already have a single value, ranges with different min/max, or
 * non-currency strings. Strips trailing "+" since the leading "from" word is
 * usually clearer in title context.
 */
export function compactFee(fee: string): string {
  if (!fee) return fee
  // Match "₹XX – ₹XX" / "₹XX-₹XX" / "₹XX — ₹XX" with same value on both sides
  const m = fee.match(/^(\s*₹\s*[\d.]+\s*[KLlk]?)\s*[–—\-]\s*(₹\s*[\d.]+\s*[KLlk]?)\s*\+?\s*$/)
  if (m && m[1].replace(/\s+/g, '') === m[2].replace(/\s+/g, '')) {
    return m[1].trim()
  }
  // Replace en/em dash inside fee range with hyphen for consistency with brand style
  return fee.replace(/\s*[–—]\s*/g, '-')
}

/**
 * Segment-aware title clamp. Sprint 1 FIX 1 rewrite.
 *
 * Invariants:
 *   1. The trailing " | brand" suffix is RESERVED first and never dropped.
 *   2. Body segments are dropped as WHOLE units (never split mid-segment).
 *      A segment is anything between two ", " separators after the first
 *      ": ". Segments to the right (lower priority) drop before segments
 *      to the left. Callers are expected to compose titles in priority
 *      order so that the fee-bearing segment sits leftmost.
 *   3. The clamped title never ends on a trailing comma, ampersand,
 *      opening bracket, or partial word.
 *
 * If the whole title already fits inside `max`, it is returned unchanged.
 * If even the anchor plus brand overflows, the anchor is trimmed at a
 * word boundary and any orphan trailing punctuation is stripped.
 */
const TRAILING_PUNCT_RE = /[,&(\[\-]+\s*$/
const HAS_OPEN_BRACKET_UNCLOSED = /\[[^\]]*$/

function stripTrailingJunk(s: string): string {
  let out = s.trim()
  // Repeatedly strip commas/ampersands/hyphens/opening brackets from tail
  while (TRAILING_PUNCT_RE.test(out)) {
    out = out.replace(TRAILING_PUNCT_RE, '').trim()
  }
  // If we left an unclosed "[" (e.g. "[Review" without the closing "]"),
  // strip that partial token so the title never ends mid-hook.
  if (HAS_OPEN_BRACKET_UNCLOSED.test(out)) {
    out = out.replace(HAS_OPEN_BRACKET_UNCLOSED, '').trim()
    out = out.replace(TRAILING_PUNCT_RE, '').trim()
  }
  return out
}

export function clampTitle(title: string, max = 60, _slug?: string): string {
  if (title.length <= max) return title

  const sepIdx = title.lastIndexOf(' | ')
  const brand  = sepIdx > 0 ? title.slice(sepIdx) : ''
  const body   = sepIdx > 0 ? title.slice(0, sepIdx) : title
  const bodyBudget = max - brand.length

  // Pathological: brand alone exceeds max. Return brand-less body trimmed.
  if (bodyBudget <= 0) {
    return stripTrailingJunk(body.substring(0, max).replace(/\s+\S*$/, ''))
  }

  // Split body into anchor (everything before the first ": ") + segments.
  const colonIdx = body.indexOf(': ')
  const anchor   = colonIdx > 0 ? body.slice(0, colonIdx) : body
  const tailRaw  = colonIdx > 0 ? body.slice(colonIdx + 2) : ''

  if (!tailRaw) {
    // No tail to drop; word-trim the anchor.
    const trimmed = body.length <= bodyBudget
      ? body
      : body.substring(0, bodyBudget).replace(/\s+\S*$/, '').trim()
    return stripTrailingJunk(trimmed) + brand
  }

  // Segments are comma-delimited by a comma FOLLOWED BY WHITESPACE. The
  // whitespace requirement is deliberate. Fee values like "₹72,661" or
  // "₹1,45,400" carry a comma inside them with no space, and must stay
  // as a single atomic token instead of being split into ["₹72", "661"].
  // Tokens like "[Review]" that follow a space (not a comma) still travel
  // with the preceding segment.
  const segments = tailRaw.split(/,\s+/)

  // Greedy drop from the RIGHT until the assembly fits.
  for (let n = segments.length; n >= 1; n--) {
    const chosen   = segments.slice(0, n)
    const assembled = `${anchor}: ${chosen.join(', ')}`
    if (assembled.length <= bodyBudget) {
      return stripTrailingJunk(assembled) + brand
    }
  }

  // Not even one segment fits. Fall back to anchor alone (word-trimmed).
  let anchorOnly = anchor
  if (anchorOnly.length > bodyBudget) {
    anchorOnly = anchorOnly.substring(0, bodyBudget).replace(/\s+\S*$/, '').trim()
  }
  return stripTrailingJunk(anchorOnly) + brand
}

/**
 * Meta description clamp. Final-sprint FIX 3.
 *
 * Contract: never cut mid-sentence. Aim for 140-160 visible chars where
 * content is available. `max` (default 160) is a soft target; a hard
 * ceiling of `max + HARD_CEILING_TOLERANCE` (default 175) lets us keep
 * a complete final sentence when it overruns the soft target by a small
 * amount rather than truncating to a shorter fragment. Any description
 * beyond the hard ceiling is clamped at the last sentence boundary
 * inside the soft target, or (fallback only) at a word boundary.
 */
const HARD_CEILING_TOLERANCE = 15  // 160 soft + 15 = 175 hard

export function clampDescription(desc: string, max = 160): string {
  if (desc.length <= max) return desc
  // Within soft-target + ceiling tolerance: keep the full desc rather
  // than dropping a trailing sentence that would land us in the 100-120c
  // "under-filled" zone.
  if (desc.length <= max + HARD_CEILING_TOLERANCE) return desc

  const slice = desc.substring(0, max)
  const lastDot  = slice.lastIndexOf('.')
  const lastExcl = slice.lastIndexOf('!')
  const lastQ    = slice.lastIndexOf('?')
  const boundary = Math.max(lastDot, lastExcl, lastQ)
  if (boundary >= Math.floor(max * 0.6)) {
    return slice.substring(0, boundary + 1).trim()
  }
  const wordTrimmed = slice.replace(/\s+\S*$/, '').trim()
  return stripTrailingJunk(wordTrimmed)
}
